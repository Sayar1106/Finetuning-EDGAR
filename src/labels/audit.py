# CLI
# ------------------------------------------------------------------------------------------------


def _cmd_sample(args: argparse.Namespace) -> None:
    if SHEET_PATH.exists() and not args.force:
        raise SystemExit(
            f"{SHEET_PATH} already exists. Re-sampling would discard the verdicts in it.\n"
            "Pass --force if that is what you want."
        )
    filings = load_labeled_filings()
    risk_rows, filing_rows = draw_sample(
        filings,
        n_filings=args.filings,
        per_filing=args.per_filing,
        seed=args.seed,
        test_filings=args.test_filings,
    )
    meta = {
        "seed": args.seed,
        "n_filings": args.filings,
        "per_filing": args.per_filing,
        "test_filings": args.test_filings,
        "population_filings": len(filings),
        "population_risks": sum(len(f.risks) for f in filings),
        "sampled_risks": len(risk_rows),
    }
    write_sheet(risk_rows, filing_rows, meta)
    print(
        f"Drew {len(risk_rows)} risks from {len(filing_rows)} filings "
        f"(population: {meta['population_risks']} risks in {meta['population_filings']} filings)."
    )
    for stratum in STRATA:
        rows = [f for f in filing_rows if f["stratum"] == stratum]
        if not rows:
            continue
        by_split = ", ".join(
            f"{sum(1 for r in rows if r['split'] == s)} {s}"
            for s in SPLITS
            if any(r["split"] == s for r in rows)
        )
        print(f"  {stratum:7s} {len(rows):2d} filings ({by_split})")
    print(f"\nWrote {SHEET_PATH.relative_to(ROOT)}")
    print("Next: python -m src.labels.audit review")


def _cmd_review(args: argparse.Namespace) -> None:
    review()


def _cmd_score(args: argparse.Namespace) -> None:
    risk_rows = _read_jsonl(SHEET_PATH)
    filing_rows = _read_jsonl(FILINGS_PATH)
    filings = load_labeled_filings()
    for stratum in STRATA:
        if not any(r.get("stratum") == stratum for r in risk_rows):
            continue
        report = score_sheet(
            risk_rows, filing_rows, filings=filings, seed=args.seed, stratum=stratum
        )
        print(format_report(report))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    p_sample = sub.add_parser("sample", help="draw a review sheet")
    p_sample.add_argument("--filings", type=int, default=DEFAULT_FILINGS)
    p_sample.add_argument("--per-filing", type=int, default=DEFAULT_PER_FILING)
    p_sample.add_argument("--seed", type=int, default=DEFAULT_SEED)
    p_sample.add_argument(
        "--test-filings",
        type=int,
        default=DEFAULT_TEST_FILINGS,
        help="extra test-split filings, scored as a separate stratum (0 to disable)",
    )
    p_sample.add_argument("--force", action="store_true", help="overwrite an existing sheet")
    p_sample.set_defaults(func=_cmd_sample)

    p_review = sub.add_parser("review", help="fill in the sheet interactively")
    p_review.set_defaults(func=_cmd_review)

    p_score = sub.add_parser("score", help="agreement rates with clustered CIs")
    p_score.add_argument("--seed", type=int, default=DEFAULT_SEED)
    p_score.set_defaults(func=_cmd_score)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    sys.exit(main())
