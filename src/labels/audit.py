"""Hand-audit of the teacher's risk-factor labels -- the measured version of "spot-checked by hand".

    python -m src.labels.audit sample     # draw a review sheet (deterministic, seeded)
    python -m src.labels.audit review     # fill it in, one risk at a time
    python -m src.labels.audit score      # agreement rates with clustered CIs

Numeric labels come from XBRL and need no audit: they are exact by construction and already checked
against the excerpt by `check_grounding`. Risk-factor labels are the opposite -- generated by Claude
Haiku, unverifiable from the data itself, and scored by src/eval/metrics.py as if they were truth.
Every risk-factor number this project reports is therefore conditional on the teacher being right,
and that conditional is untested until a human reads the filings.

Three verdicts per sampled risk, because they fail differently and the fixes differ:

  grounded    Is this risk actually stated in the text the teacher was given? A "no" is a
              hallucinated label -- it teaches the student to invent risks, and it is the one
              failure that makes the training data actively harmful rather than merely noisy.
  category    Would a human pick the same category? This is what `category_f1` and
              `category_accuracy` score, so it is the headline agreement number.
  summary     Is the summary faithful to the filing and specific to this company, rather than
              boilerplate that would fit any registrant?

Two design choices worth defending:

**The reviewer picks the category before seeing the teacher's.** Showing a label and asking "do you
agree?" measures agreement with an anchor, not independent agreement -- the reviewer accepts a
plausible-looking answer they would not have produced. `review` hides the teacher's category, takes
the human's, then compares programmatically. Grounding and summary verdicts necessarily show the
teacher's text, so only the category verdict gets this treatment; it is also the only one used as
the headline.

**The sample is clustered by filing, and so is the interval.** A uniform draw of 50 risks would land
in ~50 distinct filings, each demanding its own read of Item 1A -- hours of work for one number. So
`sample` draws filings first, then risks within them. That makes the items non-independent (one
misread section corrupts every risk under it), and `score` accordingly resamples *filings* in the
bootstrap, exactly as src/eval/metrics.py does. Treating 50 clustered items as 50 independent ones
would report an interval that is too narrow.

The completed sheet lives in docs/audit/ and is checked in. It is evidence for a claim the README
makes; a number without the worksheet behind it is the thing this file exists to replace.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from src.eval.metrics import BOOTSTRAP_CONFIDENCE, ConfidenceInterval, _percentile
from src.labels.schema import RISK_CATEGORIES, ExtractionTarget, RiskFactor

ROOT = Path(__file__).resolve().parents[2]
PROCESSED_DIR = ROOT / "data" / "processed"
AUDIT_DIR = ROOT / "docs" / "audit"

SHEET_PATH = AUDIT_DIR / "teacher_audit.jsonl"
FILINGS_PATH = AUDIT_DIR / "teacher_audit_filings.jsonl"
META_PATH = AUDIT_DIR / "teacher_audit_meta.json"

SPLITS = ("train", "val", "test")

# 12 filings x 4 risks ~= 48 items, against ~13 risks/filing. Enough to distinguish "the teacher is
# broadly right" from "the teacher is wrong a third of the time"; not enough to resolve two points
# of difference, which is why score reports an interval and not just a rate.
DEFAULT_FILINGS = 12
DEFAULT_PER_FILING = 4
DEFAULT_SEED = 0

# Two strata, scored separately and never pooled.
#
# The `random` stratum is a uniform draw over the whole corpus, so its rate is an unbiased estimate
# of label quality across the dataset -- that is the number the README's "spot-checked" claim needs.
#
# But the test split is 12 of 216 filings, so a uniform draw of 12 is expected to contain fewer than
# one of them, and this one contained zero. Test gold labels are what src/eval/metrics.py scores
# every reported risk-factor number against: if they are wrong, the headline result is wrong in a
# way no amount of corpus-wide quality can rescue. So the `test` stratum oversamples them
# deliberately. Pooling the two would bias the corpus estimate toward whatever the test split
# happens to look like, which is why `score` reports them apart.
DEFAULT_TEST_FILINGS = 3
STRATA = ("random", "test")

# A cluster bootstrap estimates between-filing variance by redrawing filings. With one filing every
# resample is identical, so the interval collapses to a point -- a partially-reviewed sheet would
# report "95% CI [100.0%, 100.0%]" off four items. That is worse than no interval, so below this
# many reviewed filings the CI is withheld and the report says why.
MIN_CLUSTERS_FOR_CI = 3
BOOTSTRAP_RESAMPLES = 10_000

RISK_SECTION_MARKER = "## Item 1A. Risk Factors"


# ------------------------------------------------------------------------------------------------
# Loading the labeled corpus
# ------------------------------------------------------------------------------------------------


@dataclass
class LabeledFiling:
    """One dataset row, unpacked into the two things an audit needs: what the teacher saw, and what
    it produced."""

    ticker: str
    accession_no: str
    split: str
    risk_text: str
    risks: list[RiskFactor]

    @property
    def risk_digest(self) -> str:
        """Fingerprint of the exact labels under audit.

        A verdict is about a specific sentence the teacher wrote. Rebuilding the dataset with a
        different excerpt budget or a re-run teacher produces different sentences at the same index,
        and silently re-pointing old verdicts at new labels would turn the worksheet into fiction.
        `score` compares this digest and refuses stale rows -- the same reasoning as the teacher
        cache key in src/labels/build.py.
        """
        payload = json.dumps([r.model_dump() for r in self.risks], sort_keys=True)
        return hashlib.sha256(payload.encode()).hexdigest()[:12]


def risk_section_of(excerpt: str) -> str:
    """The Item 1A slice of an excerpt -- the exact text the teacher was given.

    Duplicated deliberately from src/labels/build.py rather than imported: this module must show the
    reviewer what was actually labeled, and a shared helper that later changes its slicing would
    silently change what "the teacher saw" means for verdicts already recorded.
    """
    idx = excerpt.find(RISK_SECTION_MARKER)
    return excerpt[idx:] if idx != -1 else ""


def load_labeled_filings(processed_dir: Path = PROCESSED_DIR) -> list[LabeledFiling]:
    """Every labeled filing across all three splits, in a stable order.

    Filings whose Item 1A is incorporated by reference are excluded: they carry an empty risk list
    by design, so there is nothing to audit and including them would inflate the denominator with
    guaranteed-correct emptiness.
    """
    out: list[LabeledFiling] = []
    for split in SPLITS:
        path = processed_dir / f"{split}.jsonl"
        if not path.exists():
            continue
        for line in path.read_text().splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            if row.get("risk_factors_by_reference"):
                continue
            target = ExtractionTarget.model_validate_json(row["messages"][-1]["content"])
            if not target.risk_factors:
                continue
            out.append(
                LabeledFiling(
                    ticker=row["ticker"],
                    accession_no=row["accession_no"],
                    split=split,
                    risk_text=risk_section_of(row["messages"][1]["content"]),
                    risks=target.risk_factors,
                )
            )
    out.sort(key=lambda f: f.accession_no)
    return out


# ------------------------------------------------------------------------------------------------
# Sampling
# ------------------------------------------------------------------------------------------------


def draw_sample(
    filings: list[LabeledFiling],
    n_filings: int = DEFAULT_FILINGS,
    per_filing: int = DEFAULT_PER_FILING,
    seed: int = DEFAULT_SEED,
    test_filings: int = DEFAULT_TEST_FILINGS,
) -> tuple[list[dict], list[dict]]:
    """Two-stage cluster sample: filings without replacement, then risks within each.

    Returns (risk rows, filing rows). Risks within a filing are drawn at random rather than taking
    the first N: a teacher writing a list tends to put the obvious risks first, so the head of the
    list is systematically easier than the tail.

    The `test` stratum is drawn from filings the random stratum did not already take, so no filing
    is reviewed twice and no verdict is counted in both strata.
    """
    if not filings:
        raise SystemExit(
            f"No labeled filings found in {PROCESSED_DIR}. Run `python -m src.labels.build` first."
        )

    rng = random.Random(seed)
    chosen = rng.sample(filings, k=min(n_filings, len(filings)))
    strata = {f.accession_no: "random" for f in chosen}

    if test_filings:
        remaining = [f for f in filings if f.split == "test" and f.accession_no not in strata]
        extra = rng.sample(remaining, k=min(test_filings, len(remaining)))
        chosen += extra
        strata.update({f.accession_no: "test" for f in extra})

    chosen.sort(key=lambda f: (strata[f.accession_no], f.accession_no))

    risk_rows: list[dict] = []
    filing_rows: list[dict] = []
    for filing in chosen:
        stratum = strata[filing.accession_no]
        indices = sorted(rng.sample(range(len(filing.risks)), k=min(per_filing, len(filing.risks))))
        for i in indices:
            risk = filing.risks[i]
            risk_rows.append(
                {
                    "id": f"{filing.accession_no}#{i}",
                    "ticker": filing.ticker,
                    "accession_no": filing.accession_no,
                    "split": filing.split,
                    "stratum": stratum,
                    "risk_index": i,
                    "risk_digest": filing.risk_digest,
                    "teacher_title": risk.title,
                    "teacher_category": risk.category,
                    "teacher_summary": risk.summary,
                    # Filled by `review`. null means "not yet reviewed" -- distinct from false.
                    "human_category": None,
                    "grounded": None,
                    "summary_ok": None,
                    "note": "",
                }
            )
        filing_rows.append(
            {
                "accession_no": filing.accession_no,
                "ticker": filing.ticker,
                "split": filing.split,
                "stratum": stratum,
                "risk_digest": filing.risk_digest,
                "n_teacher_risks": len(filing.risks),
                "n_sampled": len(indices),
                # Recall, which per-risk precision cannot see: risks the filing discloses and the
                # teacher never emitted. Nearly free to collect -- the reviewer has just read the
                # whole section for the precision items anyway.
                "missed_risks": None,
                "note": "",
            }
        )
    return risk_rows, filing_rows


def write_sheet(risk_rows: list[dict], filing_rows: list[dict], meta: dict) -> None:
    AUDIT_DIR.mkdir(parents=True, exist_ok=True)
    _write_jsonl(SHEET_PATH, risk_rows)
    _write_jsonl(FILINGS_PATH, filing_rows)
    META_PATH.write_text(json.dumps(meta, indent=2) + "\n")


def _write_jsonl(path: Path, rows: list[dict]) -> None:
    with path.open("w") as f:
        for row in rows:
            f.write(json.dumps(row) + "\n")


def _read_jsonl(path: Path) -> list[dict]:
    if not path.exists():
        raise SystemExit(f"{path} not found. Run `python -m src.labels.audit sample` first.")
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


