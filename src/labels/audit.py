@dataclass
class AuditReport:
    stratum: Optional[str]
    n_reviewed: int
    n_total: int
    n_filings: int
    category_agreement: Optional[float]
    grounded_rate: Optional[float]
    summary_ok_rate: Optional[float]
    # (teacher category, human category) -> count, for disagreements only.
    confusions: dict[tuple[str, str], int] = field(default_factory=dict)
    missed_risks: Optional[int] = None
    teacher_risks_in_read_filings: int = 0
    cis: dict[str, ConfidenceInterval] = field(default_factory=dict)
    stale: list[str] = field(default_factory=list)

    @property
    def implied_recall(self) -> Optional[float]:
        """Teacher risks / (teacher risks + risks it missed), over fully-read filings.

        An upper bound on the teacher's true recall: a human reading Item 1A once catches omissions
        the teacher made loudly, not every risk buried in a subordinate clause.
        """
        if self.missed_risks is None or not self.teacher_risks_in_read_filings:
            return None
        total = self.teacher_risks_in_read_filings + self.missed_risks
        return self.teacher_risks_in_read_filings / total if total else None


def _rate(values: list[bool]) -> Optional[float]:
    return sum(values) / len(values) if values else None


def score_sheet(
    risk_rows: list[dict],
    filing_rows: list[dict],
    filings: Optional[list[LabeledFiling]] = None,
    n_resamples: int = BOOTSTRAP_RESAMPLES,
    seed: int = DEFAULT_SEED,
    stratum: Optional[str] = None,
) -> AuditReport:
    """Agreement rates over the reviewed rows, with filing-clustered bootstrap intervals.

    `stratum` restricts scoring to one stratum; `None` scores every row, which is only meaningful
    for a sheet drawn without oversampling (see STRATA on why the two are not pooled).

    Unreviewed rows are excluded rather than counted as agreement. A half-finished sheet should
    report a wide interval over what was actually checked, not a rate diluted toward whatever the
    unchecked rows would have been.
    """
    if stratum is not None:
        risk_rows = [r for r in risk_rows if r.get("stratum") == stratum]
        filing_rows = [f for f in filing_rows if f.get("stratum") == stratum]

    stale: list[str] = []
    if filings is not None:
        current = {f.accession_no: f.risk_digest for f in filings}
        for row in risk_rows:
            live = current.get(row["accession_no"])
            if live is not None and live != row["risk_digest"]:
                stale.append(row["id"])

    stale_ids = set(stale)
    reviewed = [
        r for r in risk_rows if r["id"] not in stale_ids and r.get("human_category") is not None
    ]

    by_filing: dict[str, list[dict]] = {}
    for row in reviewed:
        by_filing.setdefault(row["accession_no"], []).append(row)

    confusions: dict[tuple[str, str], int] = {}
    for row in reviewed:
        if row["human_category"] != row["teacher_category"]:
            key = (row["teacher_category"], row["human_category"])
            confusions[key] = confusions.get(key, 0) + 1

    read = [f for f in filing_rows if f.get("missed_risks") is not None]

    report = AuditReport(
        stratum=stratum,
        n_reviewed=len(reviewed),
        n_total=len(risk_rows),
        n_filings=len(by_filing),
        category_agreement=_rate([r["human_category"] == r["teacher_category"] for r in reviewed]),
        grounded_rate=_rate([bool(r["grounded"]) for r in reviewed if r["grounded"] is not None]),
        summary_ok_rate=_rate(
            [bool(r["summary_ok"]) for r in reviewed if r["summary_ok"] is not None]
        ),
        confusions=confusions,
        missed_risks=sum(f["missed_risks"] for f in read) if read else None,
        teacher_risks_in_read_filings=sum(f["n_teacher_risks"] for f in read),
        stale=stale,
    )
    report.cis = _bootstrap(by_filing, n_resamples=n_resamples, seed=seed)
    return report


def _bootstrap(
    by_filing: dict[str, list[dict]],
    n_resamples: int = BOOTSTRAP_RESAMPLES,
    confidence: float = BOOTSTRAP_CONFIDENCE,
    seed: int = DEFAULT_SEED,
) -> dict[str, ConfidenceInterval]:
    """Percentile bootstrap resampling **filings**, not items.

    The items are clustered: four risks drawn from one filing share a section, a reviewer's reading
    of it, and whatever the teacher misunderstood about that company. Resampling items would treat
    those four correlated outcomes as four independent ones and understate the interval.
    """
    clusters = list(by_filing.values())
    n = len(clusters)
    if n < MIN_CLUSTERS_FOR_CI or n_resamples <= 0:
        return {}

    draws: dict[str, list[float]] = {"category_agreement": [], "grounded_rate": [], "summary_ok_rate": []}
    rng = random.Random(seed)
    for _ in range(n_resamples):
        pooled = [row for _ in range(n) for row in clusters[rng.randrange(n)]]
        for key, values in (
            ("category_agreement", [r["human_category"] == r["teacher_category"] for r in pooled]),
            ("grounded_rate", [bool(r["grounded"]) for r in pooled if r["grounded"] is not None]),
            (
                "summary_ok_rate",
                [bool(r["summary_ok"]) for r in pooled if r["summary_ok"] is not None],
            ),
        ):
            rate = _rate(values)
            if rate is not None:
                draws[key].append(rate)

    tail = (1.0 - confidence) / 2.0
    out: dict[str, ConfidenceInterval] = {}
    for key, values in draws.items():
        if not values:
            continue
        values.sort()
        out[key] = ConfidenceInterval(
            low=_percentile(values, tail),
            high=_percentile(values, 1.0 - tail),
            confidence=confidence,
        )
    return out


_STRATUM_BLURB = {
    "random": "uniform draw over the corpus -- the unbiased label-quality estimate",
    "test": "oversampled test-split filings -- the gold labels the headline eval scores against",
}


def format_report(report: AuditReport) -> str:
    heading = "Teacher-label audit"
    if report.stratum:
        heading += f"  [{report.stratum} stratum: {_STRATUM_BLURB.get(report.stratum, '')}]"
    lines = ["", "=" * 68, heading]
    lines.append(
        f"  {report.n_reviewed} of {report.n_total} sampled risks reviewed, "
        f"across {report.n_filings} filing{'' if report.n_filings == 1 else 's'}"
    )
    if report.stale:
        lines.append(
            f"  {len(report.stale)} row(s) EXCLUDED as stale -- the labels changed since the sheet "
            "was drawn. Re-sample and re-review those filings."
        )
    if not report.n_reviewed:
        lines.append("\n  Nothing reviewed yet. Run `python -m src.labels.audit review`.")
        lines.append("=" * 68)
        return "\n".join(lines)

    lines.append("")
    for label, value, key in (
        ("Category agreement", report.category_agreement, "category_agreement"),
        ("Grounded in the text", report.grounded_rate, "grounded_rate"),
        ("Summary faithful", report.summary_ok_rate, "summary_ok_rate"),
    ):
        if value is None:
            continue
        ci = report.cis.get(key)
        interval = f"  95% CI {ci}" if ci else ""
        lines.append(f"  {label:22s} {value:6.1%}{interval}")
    if report.cis:
        lines.append("  Intervals are percentile bootstrap resampling filings, not items.")
    else:
        lines.append(
            f"  No intervals: {report.n_filings} reviewed filing(s) is under the "
            f"{MIN_CLUSTERS_FOR_CI}-cluster minimum, and a bootstrap over that few would report a "
            "point as if it were a range."
        )

    if report.confusions:
        lines.append("\nCategory disagreements (teacher -> human):")
        for (teacher, human), n in sorted(report.confusions.items(), key=lambda kv: -kv[1]):
            lines.append(f"  {teacher:22s} -> {human:22s} {n}")

    if report.missed_risks is not None:
        recall = report.implied_recall
        lines.append(
            f"\nRisks the teacher missed: {report.missed_risks} across "
            f"{report.teacher_risks_in_read_filings} labeled risks"
        )
        if recall is not None:
            lines.append(f"  implied recall (upper bound): {recall:.1%}")
    else:
        lines.append("\nNo filing-level recall recorded; missed-risk counts are unfilled.")

    lines.append("=" * 68)
    return "\n".join(lines)


