def _prompt_category() -> Optional[str]:
    """Blind category choice. Returns None if the reviewer wants to skip this item."""
    print("\n  Which category fits best?")
    for i, cat in enumerate(RISK_CATEGORIES, 1):
        print(f"    {i:2d}. {cat}")
    while True:
        raw = input("  number (or 's' to skip, 'q' to save and quit): ").strip().lower()
        if raw == "q":
            raise KeyboardInterrupt
        if raw == "s":
            return None
        if raw.isdigit() and 1 <= int(raw) <= len(RISK_CATEGORIES):
            return RISK_CATEGORIES[int(raw) - 1]
        print("  not a valid choice")


def _prompt_yes_no(question: str) -> bool:
    while True:
        raw = input(f"  {question} [y/n]: ").strip().lower()
        if raw in ("y", "yes"):
            return True
        if raw in ("n", "no"):
            return False
        if raw == "q":
            raise KeyboardInterrupt


def _prompt_int(question: str) -> Optional[int]:
    while True:
        raw = input(f"  {question} (integer, or 's' to skip): ").strip().lower()
        if raw == "s":
            return None
        if raw == "q":
            raise KeyboardInterrupt
        if raw.isdigit():
            return int(raw)


def review(sheet_path: Path = SHEET_PATH, filings_path: Path = FILINGS_PATH) -> None:
    """Walk the unreviewed rows, filing by filing. Saves after every item.

    Resumable by construction: an interrupted session leaves completed verdicts on disk, and the
    next run picks up at the first row whose `human_category` is still null. Auditing 50 risks is a
    couple of hours of reading; a flow that loses work on Ctrl-C would not get finished.
    """
    risk_rows = _read_jsonl(sheet_path)
    filing_rows = _read_jsonl(filings_path)
    filings = {f.accession_no: f for f in load_labeled_filings()}

    by_accession: dict[str, list[dict]] = {}
    for row in risk_rows:
        by_accession.setdefault(row["accession_no"], []).append(row)

    def save() -> None:
        _write_jsonl(sheet_path, risk_rows)
        _write_jsonl(filings_path, filing_rows)

    try:
        for filing_row in filing_rows:
            accession = filing_row["accession_no"]
            rows = by_accession.get(accession, [])
            pending = [r for r in rows if r["human_category"] is None]
            if not pending and filing_row["missed_risks"] is not None:
                continue

            filing = filings.get(accession)
            if filing is None:
                print(f"\n!! {accession} is no longer in the dataset; skipping.")
                continue

            print("\n" + "=" * 78)
            print(f"{filing_row['ticker']}  {accession}  ({filing_row['split']} split)")
            print(f"{filing_row['n_teacher_risks']} teacher labels, {len(pending)} to review here")
            print("=" * 78)
            input("Press Enter to print Item 1A (this is the exact text the teacher saw)...")
            print(filing.risk_text)

            for row in pending:
                print("\n" + "-" * 78)
                print(f"[{row['id']}]  {row['teacher_title']}")
                print(f"  summary: {row['teacher_summary']}")
                # The teacher's category is deliberately withheld until after the human commits.
                choice = _prompt_category()
                if choice is None:
                    continue
                row["human_category"] = choice
                verdict = "match" if choice == row["teacher_category"] else "DIFFERS"
                print(f"  teacher said: {row['teacher_category']}  ({verdict})")
                row["grounded"] = _prompt_yes_no("Is this risk actually stated in the text?")
                row["summary_ok"] = _prompt_yes_no("Is the summary faithful and company-specific?")
                row["note"] = input("  note (optional): ").strip()
                save()

            if filing_row["missed_risks"] is None:
                print("\n" + "-" * 78)
                missed = _prompt_int(
                    f"How many distinct risks did the teacher MISS in {filing_row['ticker']}?"
                )
                if missed is not None:
                    filing_row["missed_risks"] = missed
                    filing_row["note"] = input("  note (optional): ").strip()
                    save()
    except KeyboardInterrupt:
        save()
        print("\n\nSaved. Re-run `review` to continue where you left off.")
        return

    save()
    print("\nSheet complete. Run `python -m src.labels.audit score`.")


